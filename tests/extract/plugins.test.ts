import { expect, test } from 'vitest';
import { extractFromPlugins, getAtPath, parsePluginsFile, serializePluginsFile, setAtPath } from '../../src/core/extract/plugins.js';
import { PLUGINS_JS_TEXT } from '../helpers/miniGame.js';

const text = PLUGINS_JS_TEXT;

test('읽고 그대로 쓰면 원본과 같다', () => { expect(serializePluginsFile(parsePluginsFile(text))).toBe(text); });
test('설정값과 겹친 JSON 안쪽을 뽑는다', () => {
  const u = extractFromPlugins(parsePluginsFile(text).plugins);
  expect(u.map(x => x.source)).toEqual(['記録', '物語']);
  expect(u[0].ref).toEqual({ type: 'value', file: 'js/plugins.js', path: [0, 'parameters', 'title'] });
  expect(u[1].ref).toEqual({ type: 'value', file: 'js/plugins.js',
    path: [0, 'parameters', { key: 'list', json: true }, { key: 0, json: true }, 'label'] });
  expect(u.every(x => x.needsDecision)).toBe(true);
});
test('겹친 자리에 쓰면 다시 감싼다', () => {
  const p = parsePluginsFile(text); const u = extractFromPlugins(p.plugins);
  setAtPath(p.plugins, (u[1].ref as any).path, '이야기');
  expect(getAtPath(p.plugins, (u[1].ref as any).path)).toBe('이야기');
  expect(serializePluginsFile(p)).toBe(text.replace('物語', '이야기'));
});
test('못 읽는 파일', () => { expect(() => parsePluginsFile('hello')).toThrow('plugins.js 를 읽을 수 없습니다'); });

// Extra coverage.
test('꺼진 플러그인과 문자열로 감싼 문자열도 뽑는다', () => {
  const plugins = [{ name: 'Off', status: false, parameters: { msg: 'こんにちは', quoted: JSON.stringify('引用'), num: '12', bad: '[壊れ' } }];
  const u = extractFromPlugins(plugins);
  expect(u.map(x => x.source)).toEqual(['こんにちは', '引用', '[壊れ']);
  expect((u[1].ref as any).path).toEqual([0, 'parameters', { key: 'quoted', json: true }]);
  setAtPath(plugins, (u[1].ref as any).path, '인용');
  expect(plugins[0].parameters.quoted).toBe('"인용"');
});
test('실제 형식처럼 머리 주석과 줄바꿈이 있어도 읽는다', () => {
  const real = '// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n[\n{"name":"A","status":true,"description":"説明","parameters":{}}\n];\n';
  const p = parsePluginsFile(real);
  expect(p.prefix).toBe('// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n');
  expect(p.suffix).toBe(';\n');
  expect(p.plugins).toHaveLength(1);
});
test('한 줄에 플러그인 하나인 RPG Maker 형식은 그대로 쓰고, 바뀐 플러그인의 줄만 바뀐다', () => {
  for (const nl of ['\n', '\r\n']) {
    const real = `// Generated by RPG Maker.${nl}var $plugins =${nl}[${nl}{"name":"A","status":true,"description":"","parameters":{"t":"あ"}},${nl}{"name":"B","status":false,"description":"","parameters":{}}${nl}];${nl}`;
    const p = parsePluginsFile(real);
    expect(p.lineBreak).toBe(nl);
    expect(serializePluginsFile(p)).toBe(real);
    setAtPath(p.plugins, [0, 'parameters', 't'], '아');
    const lines = serializePluginsFile(p).split(nl);
    expect(lines.filter((l, i) => l !== real.split(nl)[i])).toEqual(['{"name":"A","status":true,"description":"","parameters":{"t":"아"}},']);
  }
  // Any other layout is written compactly, as before.
  expect(parsePluginsFile('var $plugins = [ {"name":"A"} ];').lineBreak).toBeUndefined();
});
